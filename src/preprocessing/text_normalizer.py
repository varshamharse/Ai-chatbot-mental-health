class TextNormalizer:
    """Normalizes text by expanding contractions and lowering case."""

    def __init__(self, lowercase: bool = True, expand_contractions: bool = True):
        self.lowercase = lowercase
        self.expand_contractions = expand_contractions
        self._compiled_contractions = {
            re.compile(r"\b" + re.escape(k) + r"\b", re.IGNORECASE): v
            for k, v in CONTRACTIONS_MAP.items()
        }

    def expand(self, text: str) -> str:
        """Expand common English contractions."""
        if not text:
            return ""
        for pattern, replacement in self._compiled_contractions.items():
            text = pattern.sub(replacement, text)
        return text

    def normalize(self, text: str) -> str:
        """Normalize text casing and contractions."""
        if not text:
            return ""
        if self.expand_contractions:
            text = self.expand(text)
        if self.lowercase:
            text = text.lower()
        return text
